_MISSING_REPORTED: set[str] = set()


def _report_missing(key: str) -> None:
    """缺失的 key 只往 stderr 提醒一次，绝不抛异常。"""
    if key in _MISSING_REPORTED:
        return
    _MISSING_REPORTED.add(key)
    try:
        sys.stderr.write("missing i18n key: " + key + "\n")
    except Exception:
        pass


def _report_bad_format(key: str) -> None:
    """模板占位符与实参对不上时提醒一次（开发期问题，不当场崩）。"""
    marker = "format:" + key
    if marker in _MISSING_REPORTED:
        return
    _MISSING_REPORTED.add(marker)
    try:
        sys.stderr.write("bad i18n format: " + key + "\n")
    except Exception:
        pass


def t(key: str, /, **kw: object) -> str:
    """取一条文案并按关键字参数格式化。

    参数：
        key: 文案键（域.子域.名）。
        kw: 模板里的具名占位符。
    返回：
        格式化后的文案；key 不存在时返回 «key» 并在 stderr 提醒一次。
    """
    template = _MESSAGES.get(key)
    if template is None:
        _report_missing(key)
        return "«" + key + "»"
    if not kw:
        return template
    try:
        return template.format(**kw)
    except (KeyError, IndexError, ValueError):
        _report_bad_format(key)
        return template


def tn(key: str, n: int, /, **kw: object) -> str:
    """带数量的文案；中文没有复数变化，直接把 n 传进模板。"""
    merged = dict(kw)
    merged["n"] = n
    return t(key, **merged)


def has(key: str) -> bool:
    """判断文案键是否存在。"""
    return key in _MESSAGES


def keys() -> tuple[str, ...]:
    """返回全部文案键（供测试与自检使用）。"""
    return tuple(_MESSAGES)


__all__ = ["t", "tn", "has", "keys"]
